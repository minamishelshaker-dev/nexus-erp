class ContextManager:
    """
    Manages assistant context and conversation history.
    """
    
    def __init__(self, db: AsyncSession):
        self.db = db
        self._contexts: Dict[UUID, AssistantContext] = {}
    
    async def get_or_create_context(
        self,
        tenant_id: UUID,
        user_id: UUID,
        module: AssistantModule = AssistantModule.GENERAL,
        language: str = "ar"
    ) -> AssistantContext:
        """Get or create context for a user session."""
        key = f"{tenant_id}:{user_id}"
        
        if key not in self._contexts:
            self._contexts[key] = AssistantContext(
                tenant_id=tenant_id,
                user_id=user_id,
                module=module,
                language=language
            )
        
        return self._contexts[key]
    
    async def update_context(
        self,
        tenant_id: UUID,
        user_id: UUID,
        updates: Dict[str, Any]
    ):
        """Update context with new information."""
        key = f"{tenant_id}:{user_id}"
        
        if key in self._contexts:
            context = self._contexts[key]
            for k, v in updates.items():
                if hasattr(context, k):
                    setattr(context, k, v)
    
    def add_recent_action(
        self,
        tenant_id: UUID,
        user_id: UUID,
        action: Dict[str, Any]
    ):
        """Add an action to recent actions history."""
        key = f"{tenant_id}:{user_id}"
        
        if key in self._contexts:
            context = self._contexts[key]
            context.recent_actions.append({
                **action,
                "timestamp": datetime.now().isoformat()
            })
            # Keep only last 10 actions
            context.recent_actions = context.recent_actions[-10:]


