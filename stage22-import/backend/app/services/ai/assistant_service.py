class AssistantService:
    """
    AI Assistant Service
    
    Main service for context-aware ERP assistance.
    """
    
    def __init__(self, db: AsyncSession):
        self.db = db
        self._context_manager = ContextManager(db)
        self._insight_generator = InsightGenerator(db)
        self._action_executor = ActionExecutor(db)
        
        # Caching
        self._cache: Dict[str, Any] = {}
        self._cache_ttl = 300
        
        # Rate limiting
        self._tenant_requests: Dict[UUID, List[float]] = {}
        self._rate_limit = 200  # requests per hour
    
    async def create_session(
        self,
        user_id: UUID,
        tenant_id: UUID,
        module: AssistantModule = AssistantModule.GENERAL,
        title: Optional[str] = None
    ) -> ChatSession:
        """Create a new chat session."""
        session = ChatSession(
            tenant_id=tenant_id,
            user_id=user_id,
            title=title or f"Assistant Session - {datetime.now().strftime('%Y-%m-%d %H:%M')}",
            context={"module": module.value}
        )
        self.db.add(session)
        await self.db.commit()
        await self.db.refresh(session)
        
        return session
    
    async def get_session(
        self,
        session_id: UUID,
        user_id: UUID,
        tenant_id: UUID
    ) -> Optional[ChatSession]:
        """Get a chat session scoped to its owner and active tenant."""
        if tenant_id is None:
            return None
        result = await self.db.execute(
            select(ChatSession)
            .options(selectinload(ChatSession.messages))
            .where(
                ChatSession.id == session_id,
                ChatSession.user_id == user_id,
                ChatSession.tenant_id == tenant_id,
                ChatSession.is_deleted == False
            )
        )
        return result.scalar_one_or_none()
    
    async def process_message(
        self,
        message: str,
        tenant_id: UUID,
        user_id: UUID,
        session_id: Optional[UUID] = None,
        module: AssistantModule = AssistantModule.GENERAL,
        language: str = "ar"
    ) -> AssistantResponse:
        """
        Process a user message and generate AI response.
        
        Args:
            message: User's message
            tenant_id: Tenant UUID
            user_id: User UUID
            session_id: Optional session UUID
            module: Current module context
            language: Response language
            
        Returns:
            AssistantResponse with AI response
        """
        # Check rate limit
        if not self._check_rate_limit(tenant_id):
            return AssistantResponse(
                message="Rate limit exceeded. Please try again later.",
                confidence=0.0
            )
        
        # Get or create session
        if session_id:
            session = await self.get_session(session_id, user_id, tenant_id)
        else:
            session = await self.create_session(user_id, tenant_id, module)
        
        if not session:
            return AssistantResponse(
                message="Session not found. Please start a new conversation.",
                confidence=0.0
            )
        
        # Update context
        await self._context_manager.update_context(
            tenant_id, user_id,
            {"module": module, "language": language, "session_id": session.id}
        )
        
        # Store user message
        user_msg = ChatMessage(
            session_id=session.id,
            message_type=ChatMessageType.USER,
            content=message
        )
        self.db.add(user_msg)
        await self.db.flush()
        
        # Get conversation history
        history = session.messages[-10:] if session.messages else []
        
        # Process with AI
        response = await self._process_with_ai(
            message, history, tenant_id, user_id, module, language
        )
        
        # Store assistant response
        assistant_msg = ChatMessage(
            session_id=session.id,
            message_type=ChatMessageType.ASSISTANT,
            content=response.message,
            intent=response.intent,
            entities=response.entities,
            data_results=response.data,
            prompt_tokens=0,  # Will be updated
            completion_tokens=response.tokens_used,
            total_tokens=response.tokens_used,
            model_used=response.model_used
        )
        self.db.add(assistant_msg)
        
        # Update session
        session.message_count += 2
        session.tokens_used += response.tokens_used
        
        await self.db.commit()
        
        return response
    
    async def stream_message(
        self,
        message: str,
        tenant_id: UUID,
        user_id: UUID,
        session_id: Optional[UUID] = None,
        module: AssistantModule = AssistantModule.GENERAL,
        language: str = "ar"
    ) -> AsyncGenerator[str, None]:
        """
        Stream AI response for real-time display.
        """
        try:
            import sys
            sys.path.insert(0, '/home/z/my-project')
            from z_ai_web_dev_sdk import ZAI
            
            zai = await ZAI.create()
            
            # Get context and history
            context = await self._context_manager.get_or_create_context(
                tenant_id, user_id, module, language
            )
            
            session = None
            if session_id:
                session = await self.get_session(session_id, user_id, tenant_id)
            
            if not session:
                session = await self.create_session(user_id, tenant_id, module)
            
            # Build messages
            system_prompt = self._build_system_prompt(module, context)
            messages = [{"role": "system", "content": system_prompt}]
            
            # Add conversation history
            if session.messages:
                for msg in session.messages[-5:]:
                    role = "user" if msg.message_type == ChatMessageType.USER else "assistant"
                    messages.append({"role": role, "content": msg.content})
            
            messages.append({"role": "user", "content": message})
            
            # Stream response
            full_response = ""
            async for chunk in await zai.chat.completions.create(
                messages=messages,
                stream=True,
                temperature=0.7
            ):
                if chunk.choices and chunk.choices[0].delta.content:
                    content = chunk.choices[0].delta.content
                    full_response += content
                    yield f"data: {json.dumps({'content': content})}\n\n"
            
            # Store messages
            user_msg = ChatMessage(
                session_id=session.id,
                message_type=ChatMessageType.USER,
                content=message
            )
            self.db.add(user_msg)
            
            assistant_msg = ChatMessage(
                session_id=session.id,
                message_type=ChatMessageType.ASSISTANT,
                content=full_response
            )
            self.db.add(assistant_msg)
            
            session.message_count += 2
            await self.db.commit()
            
            yield f"data: {json.dumps({'done': True, 'session_id': str(session.id)})}\n\n"
            
        except Exception as e:
            logger.error(f"Streaming error: {e}")
            yield f"data: {json.dumps({'error': str(e)})}\n\n"
    
    async def _process_with_ai(
        self,
        message: str,
        history: List[ChatMessage],
        tenant_id: UUID,
        user_id: UUID,
        module: AssistantModule,
        language: str
    ) -> AssistantResponse:
        """Process message with AI."""
        try:
            import sys
            sys.path.insert(0, '/home/z/my-project')
            from z_ai_web_dev_sdk import ZAI
            
            zai = await ZAI.create()
            
            # Build context
            context = await self._context_manager.get_or_create_context(
                tenant_id, user_id, module, language
            )
            
            # Build system prompt
            system_prompt = self._build_system_prompt(module, context)
            
            # Build messages
            messages = [{"role": "system", "content": system_prompt}]
            
            # Add conversation history
            for msg in history:
                role = "user" if msg.message_type == ChatMessageType.USER else "assistant"
                messages.append({"role": role, "content": msg.content})
            
            messages.append({"role": "user", "content": message})
            
            # Get completion
            completion = await zai.chat.completions.create(
                messages=messages,
                temperature=0.7,
                max_tokens=1500
            )
            
            response_content = completion.choices[0].message.content
            tokens_used = completion.usage.total_tokens if hasattr(completion, 'usage') else 0
            
            # Parse response for structured data
            intent, entities, actions = self._parse_response(response_content)
            
            # Generate suggestions
            suggestions = await self._generate_suggestions(message, module, tenant_id)
            
            return AssistantResponse(
                message=response_content,
                intent=intent,
                entities=entities,
                actions=actions,
                suggestions=suggestions,
                confidence=0.9,
                model_used="glm-4",
                tokens_used=tokens_used
            )
            
        except Exception as e:
            logger.error(f"AI processing error: {e}")
            
            # Fallback response
            return AssistantResponse(
                message=self._get_fallback_response(language),
                confidence=0.3
            )
    
    def _build_system_prompt(
        self,
        module: AssistantModule,
        context: AssistantContext
    ) -> str:
        """Build system prompt based on module and context."""
        base_prompt = MODULE_PROMPTS.get(module, MODULE_PROMPTS[AssistantModule.GENERAL])
        
        # Add language instruction
        language_instruction = ""
        if context.language == "ar":
            language_instruction = "\n\nAlways respond in Arabic (العربية). Use formal business language."
        else:
            language_instruction = "\n\nRespond in English."
        
        # Add context information
        context_info = f"""
Current Date: {date.today().strftime('%Y-%m-%d')}
Currency: {context.currency}
Timezone: {context.timezone}
"""
        
        # Add recent actions context
        if context.recent_actions:
            actions_str = json.dumps(context.recent_actions[-3:], default=str)
            context_info += f"\nRecent Actions: {actions_str}"
        
        return base_prompt + language_instruction + context_info
    
    def _parse_response(
        self,
        response: str
    ) -> Tuple[Optional[str], Dict[str, Any], List[ActionRecommendation]]:
        """Parse response for structured data."""
        intent = None
        entities = {}
        actions = []
        
        # Try to extract intent
        import re
        
        # Look for action patterns
        action_patterns = [
            (r"create\s+(?:a\s+)?(?:new\s+)?(\w+)", "create"),
            (r"show\s+(?:me\s+)?(?:all\s+)?(\w+)", "query"),
            (r"update\s+(?:the\s+)?(\w+)", "update"),
        ]
        
        for pattern, action_type in action_patterns:
            match = re.search(pattern, response.lower())
            if match:
                intent = action_type
                entities["target"] = match.group(1)
                break
        
        return intent, entities, actions
    
