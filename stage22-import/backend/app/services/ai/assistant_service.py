class InsightGenerator:
    """
    Generates proactive insights from ERP data.
    """
    
    def __init__(self, db: AsyncSession):
        self.db = db
    
    async def generate_insights(
        self,
        tenant_id: UUID,
        modules: Optional[List[AssistantModule]] = None
    ) -> List[ProactiveInsight]:
        """Generate proactive insights for a tenant."""
        insights = []
        
        modules = modules or list(AssistantModule)
        
        if AssistantModule.INVENTORY in modules:
            insights.extend(await self._inventory_insights(tenant_id))
        
        if AssistantModule.SALES in modules:
            insights.extend(await self._sales_insights(tenant_id))
        
        if AssistantModule.ACCOUNTING in modules:
            insights.extend(await self._accounting_insights(tenant_id))
        
        # Sort by priority
        insights.sort(key=lambda x: x.priority)
        
        return insights
    
    async def _inventory_insights(self, tenant_id: UUID) -> List[ProactiveInsight]:
        """Generate inventory-related insights."""
        insights = []
        
        # Low stock alerts
        result = await self.db.execute(
            select(Product)
            .where(
                Product.tenant_id == tenant_id,
                Product.is_deleted == False,
                Product.quantity_on_hand <= Product.reorder_point
            )
            .limit(10)
        )
        
        low_stock = result.scalars().all()
        
        if low_stock:
            insights.append(ProactiveInsight(
                insight_type=InsightType.ALERT,
                title="Low Stock Alert",
                description=f"{len(low_stock)} products are below reorder point and need attention.",
                module=AssistantModule.INVENTORY,
                priority=1,
                actionable=True,
                actions=[{
                    "type": "view",
                    "module": "inventory",
                    "filter": "low_stock"
                }, {
                    "type": "create",
                    "module": "purchase",
                    "action": "reorder",
                    "products": [str(p.id) for p in low_stock[:5]]
                }],
                data={
                    "products": [
                        {
                            "name": p.name,
                            "sku": p.sku,
                            "current_stock": float(p.quantity_on_hand),
                            "reorder_point": float(p.reorder_point)
                        }
                        for p in low_stock
                    ]
                }
            ))
        
        # Dead stock detection
        start_date = date.today() - timedelta(days=90)
        
        result = await self.db.execute(
            select(Product)
            .where(
                Product.tenant_id == tenant_id,
                Product.is_deleted == False,
                Product.quantity_on_hand > 0
            )
        )
        
        all_products = result.scalars().all()
        dead_stock = []
        
        for product in all_products:
            sales_result = await self.db.execute(
                select(func.sum(SaleOrderLine.quantity))
                .join(SaleOrder)
                .where(
                    SaleOrderLine.product_id == product.id,
                    SaleOrder.state.in_(["confirmed", "done"]),
                    SaleOrder.date_order >= start_date
                )
            )
            total_sold = sales_result.scalar() or 0
            
            if total_sold == 0 and product.quantity_on_hand > 0:
                dead_stock.append(product)
        
        if dead_stock:
            insights.append(ProactiveInsight(
                insight_type=InsightType.OPPORTUNITY,
                title="Dead Stock Identified",
                description=f"{len(dead_stock)} products have had no sales in 90 days but have stock.",
                module=AssistantModule.INVENTORY,
                priority=3,
                actionable=True,
                actions=[{
                    "type": "suggest",
                    "action": "promote",
                    "products": [str(p.id) for p in dead_stock[:5]]
                }],
                data={
                    "products": [
                        {"name": p.name, "sku": p.sku, "stock": float(p.quantity_on_hand)}
                        for p in dead_stock[:10]
                    ]
                }
            ))
        
        return insights
    
    async def _sales_insights(self, tenant_id: UUID) -> List[ProactiveInsight]:
        """Generate sales-related insights."""
        insights = []
        
        # Sales trend analysis
        today = date.today()
        this_month_start = date(today.year, today.month, 1)
        last_month_start = date(today.year, today.month - 1, 1) if today.month > 1 else date(today.year - 1, 12, 1)
        last_month_end = this_month_start - timedelta(days=1)
        
        # This month sales
        this_month_result = await self.db.execute(
            select(func.sum(SaleOrder.amount_total))
            .where(
                SaleOrder.tenant_id == tenant_id,
                SaleOrder.state.in_(["confirmed", "done"]),
                SaleOrder.date_order >= this_month_start
            )
        )
        this_month_sales = this_month_result.scalar() or 0
        
        # Last month sales
        last_month_result = await self.db.execute(
            select(func.sum(SaleOrder.amount_total))
            .where(
                SaleOrder.tenant_id == tenant_id,
                SaleOrder.state.in_(["confirmed", "done"]),
                SaleOrder.date_order >= last_month_start,
                SaleOrder.date_order <= last_month_end
            )
        )
        last_month_sales = last_month_result.scalar() or 0
        
        if last_month_sales > 0:
            change_percent = ((this_month_sales - last_month_sales) / last_month_sales) * 100
            
            if abs(change_percent) > 10:
                insight_type = InsightType.TREND
                title = "Significant Sales Trend"
                
                if change_percent > 0:
                    description = f"Sales are up {change_percent:.1f}% compared to last month."
                else:
                    description = f"Sales are down {abs(change_percent):.1f}% compared to last month."
                
                insights.append(ProactiveInsight(
                    insight_type=insight_type,
                    title=title,
                    description=description,
                    module=AssistantModule.SALES,
                    priority=2,
                    actionable=True,
                    actions=[{
                        "type": "view",
                        "module": "reports",
                        "report": "sales_comparison"
                    }],
                    data={
                        "this_month": float(this_month_sales),
                        "last_month": float(last_month_sales),
                        "change_percent": change_percent
                    }
                ))
        
        # Inactive customers
        inactive_days = 60
        start_date = date.today() - timedelta(days=inactive_days)
        
        result = await self.db.execute(
            select(Customer)
            .where(
                Customer.tenant_id == tenant_id,
                Customer.is_active == True
            )
        )
        
        customers = result.scalars().all()
        inactive_customers = []
        
        for customer in customers:
            order_result = await self.db.execute(
                select(func.max(SaleOrder.date_order))
                .where(
                    SaleOrder.partner_id == customer.id,
                    SaleOrder.tenant_id == tenant_id,
                    SaleOrder.state.in_(["confirmed", "done"])
                )
            )
            last_order = order_result.scalar()
            
            if last_order is None or last_order < start_date:
                inactive_customers.append({
                    "id": str(customer.id),
                    "name": customer.name,
                    "last_order": last_order.isoformat() if last_order else None
                })
        
        if len(inactive_customers) > 0:
            insights.append(ProactiveInsight(
                insight_type=InsightType.OPPORTUNITY,
                title="Inactive Customers",
                description=f"{len(inactive_customers)} customers haven't ordered in {inactive_days} days.",
                module=AssistantModule.CRM,
                priority=2,
                actionable=True,
                actions=[{
                    "type": "suggest",
                    "action": "follow_up",
                    "customers": inactive_customers[:10]
                }],
                data={"customers": inactive_customers}
            ))
        
        return insights
    
    async def _accounting_insights(self, tenant_id: UUID) -> List[ProactiveInsight]:
        """Generate accounting-related insights."""
        insights = []
        
        # Pending journal entries
        result = await self.db.execute(
            select(func.count(JournalEntry.id))
            .where(
                JournalEntry.tenant_id == tenant_id,
                JournalEntry.state == "draft"
            )
        )
        
        pending_entries = result.scalar() or 0
        
        if pending_entries > 10:
            insights.append(ProactiveInsight(
                insight_type=InsightType.RECOMMENDATION,
                title="Pending Journal Entries",
                description=f"{pending_entries} journal entries are pending review and posting.",
                module=AssistantModule.ACCOUNTING,
                priority=2,
                actionable=True,
                actions=[{
                    "type": "view",
                    "module": "accounting",
                    "filter": "draft_entries"
                }],
                data={"pending_count": pending_entries}
            ))
        
        return insights


