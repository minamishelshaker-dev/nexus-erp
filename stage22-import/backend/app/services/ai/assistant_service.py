    def _check_rate_limit(self, tenant_id: UUID) -> bool:
        """Check if tenant has exceeded rate limit."""
        import time
        current_time = time.time()
        
        if tenant_id not in self._tenant_requests:
            self._tenant_requests[tenant_id] = []
        
        # Clean old requests
        self._tenant_requests[tenant_id] = [
            t for t in self._tenant_requests[tenant_id]
            if current_time - t < 3600
        ]
        
        if len(self._tenant_requests[tenant_id]) >= self._rate_limit:
            return False
        
        self._tenant_requests[tenant_id].append(current_time)
        return True
    
    async def get_conversation_history(
        self,
        session_id: UUID,
        user_id: UUID,
        tenant_id: UUID,
        limit: int = 50
    ) -> List[ChatMessage]:
        """Get conversation history for a session."""
        session = await self.get_session(session_id, user_id, tenant_id)
        
        if not session:
            return []
        
        return session.messages[-limit:]
    
    async def clear_session(
        self,
        session_id: UUID,
        user_id: UUID,
        tenant_id: UUID
    ) -> bool:
        """Clear a chat session."""
        session = await self.get_session(session_id, user_id, tenant_id)
        
        if not session:
            return False
        
        session.is_active = False
        await self.db.commit()
        
        return True
