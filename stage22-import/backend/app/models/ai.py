class Forecast(BaseModel, TenantMixin):
    """
    Forecast Model (التنبؤ بالطلب)
    
    Stores demand/sales forecasts for products.
    Generated by AI forecasting service.
    """
    __tablename__ = "forecasts"
    __table_args__ = (
        Index("ix_forecasts_product", "product_id"),
        Index("ix_forecasts_date", "forecast_date"),
        Index("ix_forecasts_type", "forecast_type"),
        Index("ix_forecasts_company", "tenant_id"),
    )
    
    # Product Reference
    product_id: uuid.UUID = Column(
        UUID(as_uuid=True),
        ForeignKey("products.id", ondelete="CASCADE"),
        nullable=False,
        doc="Product being forecasted"
    )
    
    # Forecast Details
    forecast_type: ForecastType = Column(
        SQLEnum(ForecastType),
        default=ForecastType.DEMAND,
        nullable=False,
        doc="Type of forecast"
    )
    
    forecast_date: date = Column(
        Date,
        nullable=False,
        doc="Date of the forecast"
    )
    
    period_type: str = Column(
        String(20),
        default="monthly",
        nullable=False,
        doc="Period type: daily, weekly, monthly, yearly"
    )
    
    # Prediction Values
    predicted_quantity: Decimal = Column(
        Numeric(18, 4),
        nullable=False,
        doc="Predicted quantity"
    )
    
    predicted_value: Decimal = Column(
        Numeric(18, 4),
        default=Decimal("0"),
        nullable=False,
        doc="Predicted monetary value"
    )
    
    # Confidence Interval
    confidence_lower: Decimal = Column(
        Numeric(18, 4),
        nullable=True,
        doc="Lower bound of confidence interval"
    )
    
    confidence_upper: Decimal = Column(
        Numeric(18, 4),
        nullable=True,
        doc="Upper bound of confidence interval"
    )
    
    confidence_score: float = Column(
        Float,
        default=0.0,
        nullable=False,
        doc="Model confidence score (0-1)"
    )
    
    # Method Used
    method: ForecastMethod = Column(
        SQLEnum(ForecastMethod),
        default=ForecastMethod.AI_API,
        nullable=False,
        doc="Forecasting method used"
    )
    
    # Training Data Range
    data_start_date: Optional[date] = Column(Date, nullable=True)
    data_end_date: Optional[date] = Column(Date, nullable=True)
    
    # Model Info
    model_version: Optional[str] = Column(String(50), nullable=True)
    model_params: dict = Column(JSONB, default=dict, nullable=False)
    
    # Actual vs Predicted (for accuracy tracking)
    actual_quantity: Optional[Decimal] = Column(Numeric(18, 4), nullable=True)
    actual_value: Optional[Decimal] = Column(Numeric(18, 4), nullable=True)
    accuracy_score: Optional[float] = Column(Float, nullable=True)
    
    # Additional
    notes: Optional[str] = Column(Text, nullable=True)
    custom_fields: dict = Column(JSONB, default=dict, nullable=False)
    
    # ========================================
    # Relationships
    # ========================================
    # product: relationship defined in Product model
    
    # ========================================
    # Properties
    # ========================================
    
    @property
    def variance(self) -> Optional[Decimal]:
        """Calculate variance between actual and predicted."""
        if self.actual_quantity is not None:
            return self.actual_quantity - self.predicted_quantity
        return None
    
    @property
    def variance_percent(self) -> Optional[float]:
        """Calculate variance percentage."""
        if self.actual_quantity is not None and self.predicted_quantity > 0:
            return float((self.actual_quantity - self.predicted_quantity) / self.predicted_quantity * 100)
        return None


