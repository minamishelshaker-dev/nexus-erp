class ChatSession(BaseModel, TenantMixin):
    """
    Chat Session Model (جلسة المحادثة)
    
    Stores chat conversation sessions with the AI assistant.
    """
    __tablename__ = "chat_sessions"
    __table_args__ = (
        Index("ix_chat_sessions_user", "user_id"),
        Index("ix_chat_sessions_company", "tenant_id"),
    )
    
    # User Reference
    user_id: uuid.UUID = Column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        doc="User who started the session"
    )
    
    # Session Info
    title: Optional[str] = Column(
        String(255),
        nullable=True,
        doc="Session title (auto-generated or user-defined)"
    )
    
    context: dict = Column(
        JSONB,
        default=dict,
        nullable=False,
        doc="Session context (current page, filters, etc.)"
    )
    
    # Status
    is_active: bool = Column(
        Boolean,
        default=True,
        nullable=False,
        doc="Whether session is active"
    )
    
    # Summary
    message_count: int = Column(
        Integer,
        default=0,
        nullable=False,
        doc="Total number of messages"
    )
    
    tokens_used: int = Column(
        Integer,
        default=0,
        nullable=False,
        doc="Total tokens used in the session"
    )
    
    # Additional
    metadata_json: dict = Column("metadata", JSONB, default=dict, nullable=False)
    
    # ========================================
    # Relationships
    # ========================================
    messages: Mapped[List["ChatMessage"]] = relationship(
        "ChatMessage",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="ChatMessage.created_at"
    )
    
    # ========================================
    # Properties
    # ========================================
    
    @property
    def last_message(self) -> Optional["ChatMessage"]:
        """Get the last message in the session."""
        if self.messages:
            return self.messages[-1]
        return None


